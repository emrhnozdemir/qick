class QTagSweepProgram(AveragerProgramV2):
    
    def _initialize(self, cfg):
        # --- OPCODE 0: Set Bounds ---
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's1', 'SRC': 'imm', 'LIT': f'#{cfg["start_freq"]}'})
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's2', 'SRC': 'imm', 'LIT': f'#{cfg["stop_freq"]}'})
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's3', 'SRC': 'imm', 'LIT': f'#{cfg["averager_value"]}'})
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's4', 'SRC': 'imm', 'LIT': f'#{cfg["first_sweep_step"]}'})
        self.asm_inst({'CMD': 'PB', 'C_OP': '0', 'R1': 's1', 'R2': 's2', 'R3': 's3', 'R4': 's4'})
        
        # --- OPCODE 3: Set Sweep Steps ---
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's1', 'SRC': 'imm', 'LIT': '#0'})
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's2', 'SRC': 'imm', 'LIT': f'#{cfg["second_sweep_step"]}'})
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's3', 'SRC': 'imm', 'LIT': f'#{cfg["second_sweep_window"]}'})
        self.asm_inst({'CMD': 'REG_WR', 'DST': 's4', 'SRC': 'imm', 'LIT': '#0'})
        self.asm_inst({'CMD': 'PB', 'C_OP': '3', 'R1': 's1', 'R2': 's2', 'R3': 's3', 'R4': 's4'})

    def _body(self, cfg):
        # Trigger the hardware (OP=1)
        self.asm_inst({'CMD': 'PB', 'C_OP': '1', 'R1': 's0', 'R2': 's0', 'R3': 's0', 'R4': 's0'})
        
        self.wait(1.0) 
        
        # Read the outputs (OP=2)
        self.asm_inst({'CMD': 'PB', 'C_OP': '2', 'R1': 's0', 'R2': 's0', 'R3': 's0', 'R4': 's0'})
        
        self.write_dmem(addr=0, src='s_core_r1') 
        self.write_dmem(addr=1, src='s_core_r2') 

    # -------------------------------------------------------------------
    # TA'S ASSEMBLY CODE EXTRACTOR
    # -------------------------------------------------------------------
    def export_assembly(self):
        """
        Translates the internal Python compiler dictionaries into 
        standard, readable tProc Assembly Code.
        """
        asm_text = "// --- tProc V2 Assembly Code for Custom Module ---\n"
        asm_text += "// Generated by QICK Python Assembler\n\n"
        
        for idx, inst in enumerate(self.prog_list):
            cmd = inst.get('CMD')
            line = f"[{idx:03d}]: "
            
            # Format standard register writes
            if cmd == 'REG_WR':
                dst = inst.get('DST')
                lit = inst.get('LIT')
                line += f"REG_WR  {dst}, {lit}"
                
            # Format the Peripheral Bus command
            elif cmd == 'PB':
                op = inst.get('C_OP')
                r1 = inst.get('R1', 's0')
                r2 = inst.get('R2', 's0')
                r3 = inst.get('R3', 's0')
                r4 = inst.get('R4', 's0')
                line += f"PB      {op}, {r1}, {r2}, {r3}, {r4}"
                
            # Format the Wait command
            elif cmd == 'WAIT':
                time_val = inst.get('TIME', '@0')
                line += f"WAIT    {time_val}"
                
            # Format Data Memory Writes
            elif cmd == 'DMEM_WR':
                addr = inst.get('ADDR', '0')
                src = inst.get('SRC', 's_core_r1')
                line += f"DMEM_WR [{addr}], {src}"
                
            else:
                line += f"{cmd} {inst}"
                
            asm_text += line + "\n"

        # Save to a .asm file
        with open("qtag_program.asm", "w") as file:
            file.write(asm_text)
        print("[+] Dumped readable Assembly Code to 'qtag_program.asm'")


