# 1. Generate the TA's readable Assembly Code (.asm)
prog.export_assembly()

# 2. Generate the real PMEM Hex for Vivado Simulation (.mem)
pmem_hex = ""
for hex_line in prog.binprog['pmem']:
    if isinstance(hex_line, (list, np.ndarray)):
        val = (int(hex_line[2]) << 64) | (int(hex_line[1]) << 32) | int(hex_line[0])
    else:
        val = hex_line
    pmem_hex += f"{val:018x}\n"

with open("qtag_pmem_for_vivado.mem", "w") as file:
    file.write(pmem_hex)
print("[+] Saved real machine code to 'qtag_pmem_for_vivado.mem'")